const STORAGE_KEY = "tradenews_copy_trading_bots_v1";

export function loadStoredBots(): BotTrader[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return INITIAL_20_BOTS;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length === 20) {
      // Merge with initial bots to ensure any new structure is intact
      return INITIAL_20_BOTS.map((initial) => {
        const saved = parsed.find((p: BotTrader) => p.id === initial.id);
        if (!saved) return initial;
        return {
          ...initial,
          ...saved,
          basket: saved.basket || initial.basket,
          openPositions: saved.openPositions || [],
          recentTrades: saved.recentTrades || [],
        };
      });
    }
  } catch {}
  return INITIAL_20_BOTS;
}

export function saveStoredBots(bots: BotTrader[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(bots));
  } catch {}
}

export function formatSecondsToClock(seconds: number): string {
  const hrs = Math.floor(seconds / 3600);
  const mins = Math.floor((seconds % 3600) / 60);
  const secs = seconds % 60;
  return `${hrs.toString().padStart(2, "0")}:${mins.toString().padStart(2, "0")}:${secs.toString().padStart(2, "0")}`;
}

const LAST_ACTIVE_BOT_KEY = "tradenews_last_active_bot_id";

export function getLastActiveBotId(): string | null {
  try {
    return localStorage.getItem(LAST_ACTIVE_BOT_KEY);
  } catch {
    return null;
  }
}

export function setLastActiveBotId(botId: string): void {
  try {
    localStorage.setItem(LAST_ACTIVE_BOT_KEY, botId);
    if (typeof window !== "undefined") {
      window.dispatchEvent(new CustomEvent("tradenews_active_bot_changed", { detail: { botId } }));
    }
  } catch {}
}

